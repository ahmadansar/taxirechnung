const dicts = { de, en }
export type Lang = keyof typeof dicts

function initialLang(): Lang {
  try {
    const s = localStorage.getItem('taxirechnung:lang')
    if (s === 'de' || s === 'en') return s
  } catch {
    /* ignore */
  }
  return navigator.language?.startsWith('de') ? 'de' : navigator.language ? 'en' : 'de'
}

interface Ctx {
  lang: Lang
  setLang: (l: Lang) => void
  t: (k: TKey) => string
  /** translate an error message if we know it */
  te: (e: unknown) => string
}
const I18nCtx = createContext<Ctx>(null as unknown as Ctx)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang)
  const setLang = (l: Lang) => {
    setLangState(l)
    try {
      localStorage.setItem('taxirechnung:lang', l)
    } catch {
      /* ignore */
    }
    document.documentElement.lang = l
  }
  const t = (k: TKey) => dicts[lang][k] ?? k
  const te = (e: unknown) => {
    const m = e instanceof Error ? e.message : String(e)
    return (dicts[lang] as Record<string, string>)[m] ?? m
  }
  return <I18nCtx.Provider value={{ lang, setLang, t, te }}>{children}</I18nCtx.Provider>
}

// eslint-disable-next-line react-refresh/only-export-components
export const useI18n = () => useContext(I18nCtx)
